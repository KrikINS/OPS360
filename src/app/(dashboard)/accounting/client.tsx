// ── Journal Ledger Drill-Down Row (B10) ─────────────
// Self-contained component: manages its own expand/collapse state and
// fetches the debit/credit lines on-demand when the user clicks.
type JournalLine = {
  id: string
  accountCode: string
  accountName: string
  accountType: string
  debit: number
  credit: number
  description: string
}

function JournalEntryRow({ entry, isAdmin, onSuccess }: { entry: JournalEntry; isAdmin: boolean; onSuccess: () => void }) {
  const [isOpen, setIsOpen] = useState(false)
  const [lines, setLines] = useState<JournalLine[]>([])
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  // Edit Modal State
  const [editModalOpen, setEditModalOpen] = useState(false)
  const [editReason, setEditReason] = useState('')
  const [editDate, setEditDate] = useState(
    entry.date instanceof Date ? entry.date.toISOString().slice(0, 10) : String(entry.date).slice(0, 10)
  )
  const [editDescription, setEditDescription] = useState(entry.description)
  const [editLines, setEditLines] = useState<JournalLine[]>([])
  const [editing, setEditing] = useState(false)
  const [editError, setEditError] = useState('')
  const [editAccounts, setEditAccounts] = useState<Array<{code: string; name: string; type: string}> | null>(null)

  async function handleOpenEdit() {
    setEditDate(entry.date instanceof Date ? entry.date.toISOString().slice(0, 10) : String(entry.date).slice(0, 10))
    setEditDescription(entry.description)
    setEditReason('')
    setEditError('')
    setEditModalOpen(true)

    // Fetch lines if not already loaded
    // (user may not have expanded the row first)
    let linesToEdit = lines
    if (linesToEdit.length === 0) {
      try {
        const res = await getJournalLines(
          { journalEntryId: entry.id })
        if (res.success) {
          setLines(res.lines)   // also update the expand view
          linesToEdit = res.lines
        }
      } catch {
        // leave empty — dialog will show no lines
      }
    }
    setEditLines(linesToEdit.map(l => ({ ...l })))

    // Fetch accounts in parallel (non-blocking)
    getActiveAccounts().then(res => {
      setEditAccounts(res.success ? res.accounts : [])
    })
  }

  async function handleSaveEdit() {
    setEditError('')
    if (!editReason.trim()) {
      setEditError("Correction reason is required.")
      return
    }
    const totalD = editLines.reduce((s, l) => s + (Number(l.debit) || 0), 0)
    const totalC = editLines.reduce((s, l) => s + (Number(l.credit) || 0), 0)
    if (Math.abs(totalD - totalC) > 0.01) {
      setEditError(`Unbalanced: Debits (${totalD}) ≠ Credits (${totalC})`)
      return
    }
    
    setEditing(true)
    try {
      const payload = {
        id: entry.id,
        date: editDate,
        description: editDescription,
        editReason,
        lines: editLines.map(l => ({
          accountCode: l.accountCode,
          debit: Number(l.debit) || 0,
          credit: Number(l.credit) || 0,
          description: l.description
        }))
      }
      const res = await editJournalEntry(payload)
      if (res.success) {
        setEditModalOpen(false)
        setIsOpen(false) // collapse to force reload
        onSuccess()
      } else {
        setEditError('error' in res ? res.error : 'Failed to edit entry')
      }
    } catch (e) {
      setEditError((e as Error).message)
    } finally {
      setEditing(false)
    }
  }

  async function handleToggle() {
    if (isOpen) {
      setIsOpen(false)
      return
    }
    // Only fetch if we haven't already
    if (lines.length === 0) {
      setLoading(true)
      setError('')
      try {
        const res = await getJournalLines({ journalEntryId: entry.id })
        if (res.success) {
          setLines(res.lines)
        } else {
          setError(res.error ?? 'Failed to load journal lines: Unknown server error')
        }
      } catch (e: any) {
        setError('Failed to load journal lines: ' + (e?.message || String(e)))
      } finally {
        setLoading(false)
      }
    }
    setIsOpen(true)
  }

  return (
    <>
      <TableRow
        className="cursor-pointer hover:bg-slate-50/80 transition-colors"
        onClick={handleToggle}
      >
        <TableCell className="w-8 px-2">
          {isOpen
            ? <ChevronDown className="h-4 w-4 text-indigo-500" />
            : <ChevronRight className="h-4 w-4 text-slate-400" />}
        </TableCell>
        <TableCell className="text-xs text-muted-foreground whitespace-nowrap">
          {fmtDate(entry.date)}
        </TableCell>
        <TableCell className="text-sm max-w-xs truncate">
          {entry.description}
        </TableCell>
        <TableCell>
          <Badge variant="outline" className={`text-xs ${sourceColor(entry.referenceSource)}`}>
            {entry.referenceSource}
          </Badge>
        </TableCell>
        <TableCell className="text-xs text-muted-foreground">
          {entry.branchName ?? '—'}
        </TableCell>
        <TableCell className="text-xs text-muted-foreground">
          {entry.financialYear}
        </TableCell>
        <TableCell>
          <Badge variant="outline" className="text-xs">
            {entry.autoGenerated ? 'Auto' : 'Manual'}
          </Badge>
        </TableCell>
        <TableCell className="text-sm font-semibold text-slate-700 text-right tabular-nums">
          {fmtINR(entry.amount)}
        </TableCell>
        <TableCell>
          <Badge variant="outline" className={`text-xs ${statusColor(entry.status)}`}>
            {entry.status}
          </Badge>
        </TableCell>
      </TableRow>

      {/* ── Expanded detail sub-row ── */}
      {isOpen && (
        <TableRow className="bg-slate-50/60">
          <TableCell colSpan={9} className="p-0">
            <div className="px-8 py-4 border-l-4 border-indigo-300">
              {loading ? (
                <div className="flex items-center gap-2 text-sm text-muted-foreground py-2">
                  <Loader2 className="h-4 w-4 animate-spin" />
                  Loading journal lines…
                </div>
              ) : error ? (
                <p className="text-sm text-red-500 py-2">{error}</p>
              ) : lines.length === 0 ? (
                <p className="text-sm text-muted-foreground py-2">No lines recorded for this entry.</p>
              ) : (
                <div className="w-full">
                  {entry.editReason && (
                    <div className="mb-4 p-3 bg-amber-50/50 border border-amber-200 rounded-md text-amber-800 text-xs">
                      <span className="font-semibold block mb-1">Edited on {fmtDate(entry.editedAt || new Date())}</span>
                      <span className="opacity-90">Reason: {entry.editReason}</span>
                    </div>
                  )}
                  <div className="flex justify-between items-center mb-3">
                    <h4 className="font-medium text-slate-700 text-sm">Journal Lines</h4>
                    {isAdmin && !entry.autoGenerated && (
                      <Button variant="outline" size="sm" onClick={handleOpenEdit} className="h-7 text-xs bg-white">
                        <PenLine className="h-3 w-3 mr-2" />
                        Edit Entry
                      </Button>
                    )}
                  </div>
                  <table className="w-full text-sm">
                    <thead>
                    <tr className="text-xs text-muted-foreground border-b">
                      <th className="text-left py-1.5 pr-4 font-medium">Account</th>
                      <th className="text-left py-1.5 pr-4 font-medium">Description</th>
                      <th className="text-right py-1.5 pr-4 font-medium w-28">Debit (₹)</th>
                      <th className="text-right py-1.5 font-medium w-28">Credit (₹)</th>
                    </tr>
                  </thead>
                  <tbody>
                    {lines.map((line) => (
                      <tr key={line.id} className="border-b border-slate-100 last:border-0">
                        <td className="py-1.5 pr-4">
                          <span className="font-mono text-xs text-slate-500 mr-1.5">{line.accountCode}</span>
                          <span className="text-slate-700">{line.accountName}</span>
                        </td>
                        <td className="py-1.5 pr-4 text-muted-foreground max-w-xs truncate">
                          {line.description || '—'}
                        </td>
                        <td className={`py-1.5 pr-4 text-right tabular-nums font-medium ${
                          line.debit > 0 ? 'text-rose-600' : 'text-slate-300'
                        }`}>
                          {line.debit > 0 ? fmtINR(line.debit) : '—'}
                        </td>
                        <td className={`py-1.5 text-right tabular-nums font-medium ${
                          line.credit > 0 ? 'text-emerald-600' : 'text-slate-300'
                        }`}>
                          {line.credit > 0 ? fmtINR(line.credit) : '—'}
                        </td>
                      </tr>
                    ))}
                    {/* Totals footer */}
                    <tr className="border-t-2 border-slate-200 font-semibold">
                      <td colSpan={2} className="py-1.5 pr-4 text-right text-xs text-muted-foreground">Total</td>
                      <td className="py-1.5 pr-4 text-right tabular-nums text-rose-700">
                        {fmtINR(lines.reduce((s, l) => s + l.debit, 0))}
                      </td>
                      <td className="py-1.5 text-right tabular-nums text-emerald-700">
                        {fmtINR(lines.reduce((s, l) => s + l.credit, 0))}
                      </td>
                    </tr>
                  </tbody>
                </table>
              </div>
              )}
            </div>
          </TableCell>
        </TableRow>
      )}

      {/* Edit Modal */}
      {/* Edit Journal Entry — Sheet Drawer */}
      <Sheet open={editModalOpen}
        onOpenChange={setEditModalOpen}>
        <SheetContent side="right"
          className="!w-[50vw] !min-w-[520px]
            flex flex-col p-0 overflow-hidden">

          {/* Header */}
          <SheetHeader className="px-6 py-4 border-b
            border-slate-100 bg-slate-50/60 flex-shrink-0">
            <SheetTitle className="flex items-center
              gap-2 text-base font-semibold">
              Edit Journal Entry
            </SheetTitle>
            <SheetDescription className="text-xs
              text-slate-500 mt-0.5">
              Correct this entry. A reason is required
              for audit trail. Debits must equal credits.
            </SheetDescription>
          </SheetHeader>

          {/* Scrollable body */}
          <div className="flex-1 overflow-y-auto
            px-6 py-5 space-y-5">

            {/* Date & Description */}
            <div className="grid grid-cols-12 gap-4">
              <div className="col-span-4 space-y-2">
                <Label className="text-sm font-semibold text-slate-600">Date</Label>
                <Input
                  type="date"
                  value={editDate}
                  onChange={e => setEditDate(e.target.value)}
                  className="h-10 text-sm w-full"
                />
              </div>
              <div className="col-span-8 space-y-2">
                <Label className="text-sm font-semibold text-slate-600">Description</Label>
                <Input
                  value={editDescription}
                  onChange={e => setEditDescription(e.target.value)}
                  className="h-10 text-sm"
                />
              </div>
            </div>

            {/* Journal Lines */}
            <div className="space-y-3">
              {/* Column headers */}
              <div className="grid grid-cols-12 gap-3 px-1">
                <span className="col-span-6 text-xs
                  font-bold text-slate-500 uppercase
                  tracking-widest">Account</span>
                <span className="col-span-2 text-xs
                  font-bold text-slate-500 uppercase
                  tracking-widest text-right pr-2">
                  Debit (₹)</span>
                <span className="col-span-3 text-xs
                  font-bold text-slate-500 uppercase
                  tracking-widest text-right pr-2">
                  Credit (₹)</span>
                <span className="col-span-1" />
              </div>

              {/* Line cards */}
              {editLines.map((line, i) => (
                <div key={i}
                  className="grid grid-cols-12 gap-4
                    items-start px-4 py-3 rounded-xl
                    border border-slate-200 bg-white
                    hover:border-slate-300 transition-colors">

                  {/* Account */}
                  <div className="col-span-6 space-y-2">
                    <AccountCombobox
                      accounts={editAccounts}
                      value={line.accountCode}
                      onChange={(code) => {
                        const nl = [...editLines]
                        nl[i] = { ...nl[i],
                          accountCode: code }
                        setEditLines(nl)
                      }}
                    />
                  </div>

                  {/* Debit */}
                  <div className="col-span-2">
                    <Input
                      type="number" min="0" step="0.01"
                      value={line.debit}
                      onChange={e => {
                        const nl = [...editLines]
                        nl[i].debit =
                          parseFloat(e.target.value) || 0
                        setEditLines(nl)
                      }}
                      placeholder="0.00"
                      className="h-10 text-sm text-right
                        font-mono tabular-nums w-full"
                    />
                  </div>

                  {/* Credit */}
                  <div className="col-span-3">
                    <Input
                      type="number" min="0" step="0.01"
                      value={line.credit}
                      onChange={e => {
                        const nl = [...editLines]
                        nl[i].credit =
                          parseFloat(e.target.value) || 0
                        setEditLines(nl)
                      }}
                      placeholder="0.00"
                      className="h-10 text-sm text-right
                        font-mono tabular-nums w-full"
                    />
                  </div>

                  {/* Delete */}
                  <div className="col-span-1 flex
                    justify-center pt-2.5">
                    <button
                      onClick={() => setEditLines(
                        editLines.filter((_, j) =>
                          j !== i))}
                      className="text-slate-300
                        hover:text-red-400 transition-colors">
                      <Trash2 className="h-4 w-4" />
                    </button>
                  </div>
                </div>
              ))}

              {/* Add Line button */}
              <button
                onClick={() => setEditLines([
                  ...editLines,
                  {
                    id: crypto.randomUUID(),
                    accountCode: '',
                    accountName: '',
                    accountType: '',
                    debit: 0,
                    credit: 0,
                    description: '',
                  }
                ])}
                className="flex items-center gap-2
                  text-xs text-indigo-600
                  hover:text-indigo-800 font-medium
                  py-2 px-1 transition-colors">
                <Plus className="h-3.5 w-3.5" />
                Add Line
              </button>
            </div>

            {/* Correction Reason */}
            <div className="space-y-2">
              <Label className="text-sm font-semibold
                text-rose-600">
                Correction Reason
                <span className="text-xs font-normal
                  text-slate-400 ml-1">
                  (required for audit)
                </span>
              </Label>
              <Textarea
                value={editReason}
                onChange={e =>
                  setEditReason(e.target.value)}
                placeholder="State clearly why this
                  entry is being edited..."
                className="resize-none text-sm
                  min-h-[80px]"
              />
            </div>

            {/* Error */}
            {editError && (
              <p className="text-sm text-red-500
                font-medium">{editError}</p>
            )}
          </div>

          {/* Footer */}
          <div className="flex-shrink-0 px-6 py-4
            border-t border-slate-100 bg-slate-50/40
            flex items-center justify-between">

            {/* Live totals */}
            <div className="flex items-center gap-3
              text-sm font-mono">
              <span className="text-slate-500">DR:
                <span className="font-semibold
                  text-blue-700 ml-1">
                  {fmtINR(editLines.reduce(
                    (s,l) => s + (Number(l.debit)||0), 0))}
                </span>
              </span>
              <span className="text-slate-300">=</span>
              <span className="text-slate-500">CR:
                <span className="font-semibold
                  text-green-700 ml-1">
                  {fmtINR(editLines.reduce(
                    (s,l) => s + (Number(l.credit)||0), 0))}
                </span>
              </span>
            </div>

            {/* Actions */}
            <div className="flex gap-3">
              <Button variant="outline"
                onClick={() => setEditModalOpen(false)}
                disabled={editing}>
                Cancel
              </Button>
              <Button
                onClick={handleSaveEdit}
                disabled={editing || !editReason.trim()}
                className="bg-indigo-600
                  hover:bg-indigo-700 text-white
                  min-w-[120px]">
                {editing
                  ? <Loader2 className="h-4 w-4
                      animate-spin" />
                  : 'Save Changes'}
              </Button>
            </div>
          </div>

        </SheetContent>
      </Sheet>
    </>
  )
}
