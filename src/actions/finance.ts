// ── getJournalEntries ───────────────────────────────
// Supports keyset (cursor) pagination: pass cursor.lastDate + cursor.lastId
// from the previous batch to fetch the next page. Returns hasMore + nextCursor
// so the frontend knows when to stop.
const JOURNAL_PAGE_SIZE = 50

export async function getJournalEntries(input?: {
  branchId?: string
  fromDate?: string
  toDate?: string
  source?: string
  cursor?: { lastDate: string; lastId: string }
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  try {
    // Single query with LEFT JOIN + GROUP BY (B9 fix).
    // Keyset pagination condition: fetch rows strictly "before" the cursor
    // in the (date DESC, id DESC) sort order (B8 fix).
    const rows = await db.execute(sql`
      SELECT
        je.id,
        je.date,
        je.description,
        je.reference_source   AS "referenceSource",
        je.reference_id       AS "referenceId",
        je.branch_id          AS "branchId",
        je.financial_year      AS "financialYear",
        je.status,
        je.auto_generated      AS "autoGenerated",
        je.edited_at           AS "editedAt",
        je.edit_reason         AS "editReason",
        b.name                AS "branchName",
        COALESCE(SUM(jl.debit), 0)::numeric AS amount
      FROM journal_entries je
      LEFT JOIN branches b ON b.id = je.branch_id
      LEFT JOIN journal_lines jl ON jl.journal_entry_id = je.id
      WHERE 1 = 1
        ${input?.branchId ? sql`AND je.branch_id = ${input.branchId}::uuid` : sql``}
        ${input?.fromDate ? sql`AND je.date >= ${input.fromDate}::timestamp` : sql``}
        ${input?.toDate ? sql`AND je.date <= ${input.toDate}::timestamp + interval '1 day' - interval '1 second'` : sql``}
        ${input?.cursor?.lastDate && input?.cursor?.lastId
          ? sql`AND (je.date < ${input.cursor.lastDate}::timestamp OR (je.date = ${input.cursor.lastDate}::timestamp AND je.id < ${input.cursor.lastId}::uuid))`
          : sql``}
      GROUP BY je.id, b.name
      ORDER BY je.date DESC, je.id DESC
      LIMIT ${JOURNAL_PAGE_SIZE + 1}
    `)

    // Normalise the pg result shape (rows array)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const data: any[] = (rows as any).rows ?? rows

    // If we got PAGE_SIZE+1 rows, there are more pages
    const hasMore = data.length > JOURNAL_PAGE_SIZE
    const page = hasMore ? data.slice(0, JOURNAL_PAGE_SIZE) : data

    const entries = page.map((r) => ({
      id:              r.id,
      date:            r.date,
      description:     r.description,
      referenceSource: r.referenceSource,
      referenceId:     r.referenceId,
      branchId:        r.branchId,
      financialYear:   r.financialYear,
      status:          r.status,
      autoGenerated:   r.autoGenerated,
      branchName:      r.branchName,
      amount:          Number(r.amount ?? 0),
    }))

    // Build cursor for the next page from the last entry in this batch
    const lastEntry = entries[entries.length - 1]
    const nextCursor = lastEntry
      ? { lastDate: new Date(lastEntry.date).toISOString(), lastId: lastEntry.id }
      : undefined

    return { success: true as const, entries, hasMore, nextCursor }
  } catch (error) {
    return { success: false as const, error: (error as Error).message }
  }
}

