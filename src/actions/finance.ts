// ── Helper: derive Indian financial year ────────────
export async function getFinancialYear(date: Date): Promise<string> {
  const month = date.getMonth() + 1
  const year = date.getFullYear()
  if (month >= 4) return `${year}-${String(year + 1).slice(2)}`
  return `${year - 1}-${String(year).slice(2)}`
}

// ── Helper: resolve account code → id ───────────────
async function getAccountId(code: string, txClient: any = db): Promise<string> {
  const [account] = await db
    .select({ id: accounts.id })
    .from(accounts)
    .where(eq(accounts.code, code))
    .limit(1)
  if (!account) throw new Error(`Account ${code} not found`)
  return account.id
}

// ── Helper: resolve branch-scoped cash account code ─
// Looks for a branch-specific cash account (code like '1010-%' with
// matching branch_id). Falls back to global '1010' for backward
// compatibility when no branch-scoped account exists.
export async function getCashAccountCode(branchId?: string | null): Promise<string> {
  if (!branchId) return '1010'

  const [branchAccount] = await db
    .select({ code: accounts.code })
    .from(accounts)
    .where(
      and(
        sql`${accounts.code} LIKE '1010-%'`,
        eq(accounts.branch_id, branchId),
        eq(accounts.is_active, true),
      )
    )
    .limit(1)

  return branchAccount?.code ?? '1010'
}

// ── createJournalEntry ──────────────────────────────
export async function createJournalEntry(input: {
  date?: Date
  description: string
  referenceSource: string
  referenceId?: string
  branchId: string
  autoGenerated?: boolean
  createdBy: string
  lines: Array<{
    accountCode: string
    debit?: number
    credit?: number
    description?: string
  }>
}) {
  const totalDebit  = input.lines.reduce((s, l) => s + (l.debit  ?? 0), 0)
  const totalCredit = input.lines.reduce((s, l) => s + (l.credit ?? 0), 0)
  if (Math.abs(totalDebit - totalCredit) > 0.01) {
    throw new Error(
      `Journal entry is unbalanced: debits ${totalDebit} ≠ credits ${totalCredit}`
    )
  }

  const date = input.date ?? new Date()
  const financialYear = await getFinancialYear(date)

  const [entry] = await db
    .insert(journal_entries)
    .values({
      date,
      description: input.description,
      reference_source: input.referenceSource,
      reference_id: input.referenceId ?? null,
      branch_id: input.branchId,
      financial_year: financialYear,
      status: 'posted',
      auto_generated: input.autoGenerated ?? false,
      created_by: input.createdBy,
    })
    .returning()

  const lineValues = await Promise.all(
    input.lines.map(async (line) => ({
      journal_entry_id: entry.id,
      account_id: await getAccountId(line.accountCode, db),
      debit:  String(line.debit  ?? 0),
      credit: String(line.credit ?? 0),
      description: line.description ?? null,
    }))
  )

  await db.insert(journal_lines).values(lineValues)
  return entry
}

// ── postGRNJournal ──────────────────────────────────
// DR 1040 Inventory Asset, DR 1050 GST ITC (CGST/SGST/IGST), CR 2010 Payable
export async function postGRNJournal(input: {
  grnId: string
  poId: string
  branchId: string
  createdBy: string
  totalLandedCost: number
  totalCGST: number
  totalSGST: number
  totalIGST: number
}) {
  const totalGST = input.totalCGST + input.totalSGST + input.totalIGST
  const totalPayable = input.totalLandedCost + totalGST

  const [grn] = await db
    .select({ grnNumber: grn_receipts.grn_number })
    .from(grn_receipts)
    .where(eq(grn_receipts.id, input.grnId))
    .limit(1)

  const [po] = await db
    .select({ poNumber: purchase_orders.po_number })
    .from(purchase_orders)
    .where(eq(purchase_orders.id, input.poId))
    .limit(1)

  const grnRef = grn?.grnNumber ?? input.grnId
  const poRef = po?.poNumber ?? input.poId

  const lines: Array<{
    accountCode: string
    debit?: number
    credit?: number
    description: string
  }> = []

  lines.push({
    accountCode: '1040',
    debit: input.totalLandedCost,
    description: `Inventory received — ${grnRef}`,
  })

  if (input.totalCGST > 0) {
    lines.push({
      accountCode: '1051',
      debit: input.totalCGST,
      description: `CGST Input Tax Credit — ${grnRef}`,
    })
  }

  if (input.totalSGST > 0) {
    lines.push({
      accountCode: '1052',
      debit: input.totalSGST,
      description: `SGST Input Tax Credit — ${grnRef}`,
    })
  }

  if (input.totalIGST > 0) {
    lines.push({
      accountCode: '1053',
      debit: input.totalIGST,
      description: `IGST Input Tax Credit — ${grnRef}`,
    })
  }

  lines.push({
    accountCode: '2010',
    credit: totalPayable,
    description: `Payable to vendor — ${poRef}`,
  })

  await createJournalEntry({
    description: `GRN: ${grnRef} (against ${poRef}) — ₹${input.totalLandedCost.toLocaleString('en-IN')} + GST ₹${totalGST.toLocaleString('en-IN')}`,
    referenceSource: 'GRN',
    referenceId: input.grnId,
    branchId: input.branchId,
    autoGenerated: true,
    createdBy: input.createdBy,
    lines,
  })
}

// ── postSalesJournal ────────────────────────────────
// DR 1010 Cash, CR 4000 Revenue, CR GST Payable, DR 5010 COGS, CR 1040 Inventory
export async function postSalesJournal(input: {
  invoiceId: string
  branchId: string
  createdBy: string
  saleTotal: number
  subtotal: number
  cgst: number
  sgst: number
  igst: number
  cogs: number
  loyaltyDiscountAmount?: number
}) {
  // If cogs not provided, calculate from inventory
  let cogsAmount = input.cogs

  if (cogsAmount === 0 && input.invoiceId) {
    try {
      const soldUnits = await db
        .select({ landedCost: inventory.landed_cost })
        .from(inventory)
        .where(eq(inventory.invoice_id, input.invoiceId))

      cogsAmount = soldUnits.reduce(
        (sum, unit) => sum + Number(unit.landedCost ?? 0),
        0
      )
    } catch {
      // If lookup fails, COGS stays 0 — don't block journal
      cogsAmount = 0
    }
  }

  const netReceived = input.saleTotal - (input.loyaltyDiscountAmount ?? 0)
  const cashCode = await getCashAccountCode(input.branchId)

  const lines: Array<{ accountCode: string; debit?: number; credit?: number; description?: string }> = [
    { accountCode: cashCode, debit: netReceived, description: 'Cash received from POS sale' },
    { accountCode: '4000', credit: input.subtotal, description: 'Sales revenue ex-tax' },
  ]
  
  if (input.loyaltyDiscountAmount && input.loyaltyDiscountAmount > 0) {
    // Loyalty redemption: reduce the Loyalty Liability we owe the customer.
    // DR 2050 Loyalty Liability  — we owed them this; now it's settled
    // The cash line already credits only netReceived, so the liability
    // debit here completes the balance.
    lines.push({
      accountCode: '2050',
      debit: input.loyaltyDiscountAmount,
      description: 'Loyalty liability settled — points redeemed',
    })
  }

  if (input.cgst > 0) lines.push({ accountCode: '2020', credit: input.cgst, description: 'CGST collected' })
  if (input.sgst > 0) lines.push({ accountCode: '2030', credit: input.sgst, description: 'SGST collected' })
  if (input.igst > 0) lines.push({ accountCode: '2040', credit: input.igst, description: 'IGST collected' })

  if (cogsAmount > 0) {
    lines.push(
      { accountCode: '5010', debit: cogsAmount,  description: 'Cost of goods sold' },
      { accountCode: '1040', credit: cogsAmount, description: 'Inventory asset reduced' }
    )
  }

  await createJournalEntry({
    description: 'Auto: POS sale invoice',
    referenceSource: 'SALES',
    referenceId: input.invoiceId,
    branchId: input.branchId,
    autoGenerated: true,
    createdBy: input.createdBy,
    lines,
  })
}

