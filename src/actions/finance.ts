// ── editJournalEntry (Secure Audit Edit) ────────────
export async function editJournalEntry(input: {
  id: string
  description: string
  editReason: string
  lines: Array<{
    accountCode: string
    debit?: number
    credit?: number
    description?: string
  }>
}) {
  const session = await getServerSession(authOptions)
  const role = session?.user?.role?.toLowerCase()
  if (!session?.user?.id || (role !== 'admin' && role !== 'owner' && role !== 'admin/owner' && role !== 'super_admin')) {
    return { success: false, error: "Unauthorized: Only Admins or Owners can edit journal entries." }
  }

  const totalDebit = input.lines.reduce((s, l) => s + (l.debit ?? 0), 0)
  const totalCredit = input.lines.reduce((s, l) => s + (l.credit ?? 0), 0)
  if (Math.abs(totalDebit - totalCredit) > 0.01) {
    return { success: false, error: `Journal entry is unbalanced: debits ${totalDebit} ≠ credits ${totalCredit}` }
  }

  if (!input.editReason || input.editReason.trim() === "") {
    return { success: false, error: "Correction reason is mandatory for auditing purposes." }
  }

  try {
    // Transaction for safe editing
    return await db.transaction(async (tx) => {
      // 1. Fetch current entry
      const [entry] = await tx.select().from(journal_entries).where(eq(journal_entries.id, input.id))
      if (!entry) throw new Error("Journal entry not found")
      
      if (entry.auto_generated) {
        throw new Error("Cannot edit auto-generated journal entries directly. Please edit or void the originating source document.")
      }

      // 2. Fetch current lines
      const currentLines = await tx.select({
        id: journal_lines.id,
        account_id: journal_lines.account_id,
        account_code: accounts.code,
        debit: journal_lines.debit,
        credit: journal_lines.credit,
        description: journal_lines.description,
      })
      .from(journal_lines)
      .innerJoin(accounts, eq(accounts.id, journal_lines.account_id))
      .where(eq(journal_lines.journal_entry_id, input.id))

      // 3. Create snapshot
      const snapshot = {
        entry,
        lines: currentLines
      }

      // 4. Update Header
      await tx.update(journal_entries)
        .set({
          description: input.description,
          edited_at: new Date(),
          edited_by: session.user.id,
          edit_reason: input.editReason,
          original_data: snapshot,
        })
        .where(eq(journal_entries.id, input.id))

      // 5. Delete old lines
      await tx.delete(journal_lines).where(eq(journal_lines.journal_entry_id, input.id))

      // 6. Insert new lines
      const lineValues = await Promise.all(
        input.lines.map(async (line) => ({
          journal_entry_id: input.id,
          account_id: await getAccountId(line.accountCode, tx),
          debit: line.debit ? line.debit.toString() : '0',
          credit: line.credit ? line.credit.toString() : '0',
          description: line.description ?? null,
        }))
      )

      await tx.insert(journal_lines).values(lineValues)

      return { success: true }
    })
  } catch (err) {
    return { success: false, error: (err as Error).message }
  }
}

