// ── getProfitAndLoss ────────────────────────────────
export async function getProfitAndLoss(input: {
  branchId?: string
  fromDate: string
  toDate: string
  financialYear?: string
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  try {
    const rows = await db.execute(sql`
      SELECT a.code, a.name, a.type,
        COALESCE(SUM(jl.credit - jl.debit), 0) AS net
      FROM accounts a
      LEFT JOIN journal_lines jl ON jl.account_id = a.id
      LEFT JOIN journal_entries je ON je.id = jl.journal_entry_id
        AND je.status = 'posted'
        AND je.date >= ${input.fromDate}::timestamp
        AND je.date <= ${input.toDate}::timestamp
        ${input.branchId ? sql`AND je.branch_id = ${input.branchId}::uuid` : sql``}
      WHERE a.type IN ('Revenue', 'Expense')
      GROUP BY a.code, a.name, a.type
      ORDER BY a.code
    `)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const data: any[] = (rows as any).rows ?? rows
    const revenue  = data.filter(r => r.type === 'Revenue')
    const expenses = data.filter(r => r.type === 'Expense')
    const totalRevenue  = revenue.reduce((s, r)  => s + Number(r.net), 0)
    const totalExpenses = expenses.reduce((s, r) => s + Number(r.net), 0)
    return { success: true as const, revenue, expenses, totalRevenue, totalExpenses, netProfit: totalRevenue - totalExpenses }
  } catch (error) {
    return { success: false as const, error: (error as Error).message }
  }
}

// ── getBalanceSheet ─────────────────────────────────
export async function getBalanceSheet(input: { branchId?: string; asOfDate: string }) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  try {
    const rows = await db.execute(sql`
      SELECT a.code, a.name, a.type,
        COALESCE(SUM(jl.debit - jl.credit), 0) AS balance
      FROM accounts a
      LEFT JOIN journal_lines jl ON jl.account_id = a.id
      LEFT JOIN journal_entries je ON je.id = jl.journal_entry_id
        AND je.status = 'posted'
        AND je.date <= ${input.asOfDate}::timestamp
        ${input.branchId ? sql`AND je.branch_id = ${input.branchId}::uuid` : sql``}
      WHERE a.type IN ('Asset', 'Liability', 'Equity')
      GROUP BY a.code, a.name, a.type
      ORDER BY a.code
    `)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const data: any[] = (rows as any).rows ?? rows
    return {
      success: true as const,
      assets:      data.filter(r => r.type === 'Asset'),
      liabilities: data.filter(r => r.type === 'Liability'),
      equity:      data.filter(r => r.type === 'Equity'),
    }
  } catch (error) {
    return { success: false as const, error: (error as Error).message }
  }
}

// ── getGSTSummary ───────────────────────────────────
export async function getGSTSummary(input: { branchId?: string; fromDate: string; toDate: string }) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  try {
    const rows = await db.execute(sql`
      SELECT a.code, a.name,
        COALESCE(SUM(jl.credit), 0) AS collected,
        COALESCE(SUM(jl.debit),  0) AS paid
      FROM accounts a
      LEFT JOIN journal_lines jl ON jl.account_id = a.id
      LEFT JOIN journal_entries je ON je.id = jl.journal_entry_id
        AND je.status = 'posted'
        AND je.date >= ${input.fromDate}::timestamp
        AND je.date <= ${input.toDate}::timestamp
        ${input.branchId ? sql`AND je.branch_id = ${input.branchId}::uuid` : sql``}
      WHERE a.type = 'Tax'
      GROUP BY a.code, a.name
      ORDER BY a.code
    `)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const data: any[] = (rows as any).rows ?? rows
    return { success: true as const, gst: data }
  } catch (error) {
    return { success: false as const, error: (error as Error).message }
  }
}

// ── getJournalEntries ───────────────────────────────
export async function getJournalEntries(input?: { branchId?: string; fromDate?: string; toDate?: string; source?: string }) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  try {
    const entries = await db
      .select({
        id:              journal_entries.id,
        date:            journal_entries.date,
        description:     journal_entries.description,
        referenceSource: journal_entries.reference_source,
        referenceId:     journal_entries.reference_id,
        branchId:        journal_entries.branch_id,
        financialYear:   journal_entries.financial_year,
        status:          journal_entries.status,
        autoGenerated:   journal_entries.auto_generated,
        branchName:      branches.name,
      })
      .from(journal_entries)
      .leftJoin(branches, eq(journal_entries.branch_id, branches.id))
      .where(input?.branchId ? eq(journal_entries.branch_id, input.branchId) : undefined)
      .orderBy(desc(journal_entries.date))
      .limit(200)

    return { success: true as const, entries }
  } catch (error) {
    return { success: false as const, error: (error as Error).message }
  }
}

