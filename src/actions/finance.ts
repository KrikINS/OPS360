// ── Helper: derive Indian financial year ────────────
export async function getFinancialYear(date: Date): Promise<string> {
  const month = date.getMonth() + 1
  const year = date.getFullYear()
  if (month >= 4) return `${year}-${String(year + 1).slice(2)}`
  return `${year - 1}-${String(year).slice(2)}`
}

// ── Helper: resolve account code → id ───────────────
async function getAccountId(code: string): Promise<string> {
  const [account] = await db
    .select({ id: accounts.id })
    .from(accounts)
    .where(eq(accounts.code, code))
    .limit(1)
  if (!account) throw new Error(`Account ${code} not found`)
  return account.id
}

// ── createJournalEntry ──────────────────────────────
export async function createJournalEntry(input: {
  date?: Date
  description: string
  referenceSource: string
  referenceId?: string
  branchId: string
  autoGenerated?: boolean
  createdBy: string
  lines: Array<{
    accountCode: string
    debit?: number
    credit?: number
    description?: string
  }>
}) {
  const totalDebit  = input.lines.reduce((s, l) => s + (l.debit  ?? 0), 0)
  const totalCredit = input.lines.reduce((s, l) => s + (l.credit ?? 0), 0)
  if (Math.abs(totalDebit - totalCredit) > 0.01) {
    throw new Error(
      `Journal entry is unbalanced: debits ${totalDebit} ≠ credits ${totalCredit}`
    )
  }

  const date = input.date ?? new Date()
  const financialYear = await getFinancialYear(date)

  const [entry] = await db
    .insert(journal_entries)
    .values({
      date,
      description: input.description,
      reference_source: input.referenceSource,
      reference_id: input.referenceId ?? null,
      branch_id: input.branchId,
      financial_year: financialYear,
      status: 'posted',
      auto_generated: input.autoGenerated ?? false,
      created_by: input.createdBy,
    })
    .returning()

  const lineValues = await Promise.all(
    input.lines.map(async (line) => ({
      journal_entry_id: entry.id,
      account_id: await getAccountId(line.accountCode),
      debit:  String(line.debit  ?? 0),
      credit: String(line.credit ?? 0),
      description: line.description ?? null,
    }))
  )

  await db.insert(journal_lines).values(lineValues)
  return entry
}

// ── postGRNJournal ──────────────────────────────────
// DR 1040 Inventory Asset, DR 1050 GST ITC, CR 2010 Payable
export async function postGRNJournal(input: {
  grnId: string
  poId: string
  branchId: string
  createdBy: string
  totalLandedCost: number
  totalGST: number
}) {
  const totalPayable = input.totalLandedCost + input.totalGST

  await createJournalEntry({
    description: 'Auto: GRN received against PO',
    referenceSource: 'GRN',
    referenceId: input.grnId,
    branchId: input.branchId,
    autoGenerated: true,
    createdBy: input.createdBy,
    lines: [
      { accountCode: '1040', debit: input.totalLandedCost, description: 'Inventory received — landed cost' },
      { accountCode: '1050', debit: input.totalGST,        description: 'GST Input Tax Credit on purchase' },
      { accountCode: '2010', credit: totalPayable,         description: 'Accounts payable to vendor' },
    ],
  })
}

// ── postSalesJournal ────────────────────────────────
// DR 1010 Cash, CR 4000 Revenue, CR GST Payable, DR 5010 COGS, CR 1040 Inventory
export async function postSalesJournal(input: {
  invoiceId: string
  branchId: string
  createdBy: string
  saleTotal: number
  subtotal: number
  cgst: number
  sgst: number
  igst: number
  cogs: number
}) {
  // If cogs not provided, calculate from inventory
  let cogsAmount = input.cogs

  if (cogsAmount === 0 && input.invoiceId) {
    try {
      const soldUnits = await db
        .select({ landedCost: inventory.landed_cost })
        .from(inventory)
        .where(eq(inventory.invoice_id, input.invoiceId))

      cogsAmount = soldUnits.reduce(
        (sum, unit) => sum + Number(unit.landedCost ?? 0),
        0
      )
    } catch {
      // If lookup fails, COGS stays 0 — don't block journal
      cogsAmount = 0
    }
  }

  const lines: Array<{ accountCode: string; debit?: number; credit?: number; description?: string }> = [
    { accountCode: '1010', debit: input.saleTotal, description: 'Cash received from POS sale' },
    { accountCode: '4000', credit: input.subtotal, description: 'Sales revenue ex-tax' },
  ]

  if (input.cgst > 0) lines.push({ accountCode: '2020', credit: input.cgst, description: 'CGST collected' })
  if (input.sgst > 0) lines.push({ accountCode: '2030', credit: input.sgst, description: 'SGST collected' })
  if (input.igst > 0) lines.push({ accountCode: '2040', credit: input.igst, description: 'IGST collected' })

  if (cogsAmount > 0) {
    lines.push(
      { accountCode: '5010', debit: cogsAmount,  description: 'Cost of goods sold' },
      { accountCode: '1040', credit: cogsAmount, description: 'Inventory asset reduced' }
    )
  }

  await createJournalEntry({
    description: 'Auto: POS sale invoice',
    referenceSource: 'SALES',
    referenceId: input.invoiceId,
    branchId: input.branchId,
    autoGenerated: true,
    createdBy: input.createdBy,
    lines,
  })
}

// ── createExpenseRecord ─────────────────────────────
export async function createExpenseRecord(input: {
  amount: number
  expenseAccount: string
  paymentAccount?: string
  description: string
  receiptUrl?: string
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  const branchId = await getEffectiveBranchId(session)
  if (!branchId) return { success: false as const, error: 'No branch selected' }

  if (input.amount <= 0) return { success: false as const, error: 'Amount must be greater than 0' }

  try {
    await getAccountId(input.expenseAccount)
    await getAccountId(input.paymentAccount ?? '1010')
  } catch (e) {
    return { success: false as const, error: (e as Error).message }
  }

  const [record] = await db
    .insert(expense_records)
    .values({
      branch_id:       branchId,
      created_by:      session.user.id,
      amount:          String(input.amount),
      expense_account: input.expenseAccount,
      payment_account: input.paymentAccount ?? '1010',
      description:     input.description,
      receipt_url:     input.receiptUrl ?? null,
      status:          'pending',
    })
    .returning()

  return { success: true as const, record }
}

// ── approveExpense ──────────────────────────────────
export async function approveExpense(input: { expenseId: string }) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  const role = (session.user.role ?? '').toLowerCase()
  if (!['admin', 'super_admin', 'admin/owner', 'manager'].includes(role)) {
    return { success: false as const, error: 'Manager role required' }
  }

  const [expense] = await db
    .select()
    .from(expense_records)
    .where(eq(expense_records.id, input.expenseId))
    .limit(1)

  if (!expense) return { success: false as const, error: 'Expense not found' }
  if (expense.status !== 'pending') {
    return { success: false as const, error: `Cannot approve expense with status: ${expense.status}` }
  }

  const entry = await createJournalEntry({
    description: `Expense: ${expense.description}`,
    referenceSource: 'EXPENSE',
    referenceId: expense.id,
    branchId: expense.branch_id,
    autoGenerated: false,
    createdBy: session.user.id,
    lines: [
      { accountCode: expense.expense_account, debit: Number(expense.amount), description: expense.description },
      { accountCode: expense.payment_account, credit: Number(expense.amount), description: 'Payment from cash/bank' },
    ],
  })

  await db
    .update(expense_records)
    .set({ status: 'approved', approved_by: session.user.id, approved_at: new Date(), journal_entry_id: entry.id })
    .where(eq(expense_records.id, input.expenseId))

  return { success: true as const, entry }
}

