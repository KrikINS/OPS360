// ── createExpenseRecord ─────────────────────────────
export async function createExpenseRecord(input: {
  amount: number
  expenseAccount: string
  paymentAccount?: string
  description: string
  receiptUrl?: string
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  const branchId = await getEffectiveBranchId(session)
  if (!branchId) return { success: false as const, error: 'No branch selected' }

  if (input.amount <= 0) return { success: false as const, error: 'Amount must be greater than 0' }

  // Resolve the payment account: use branch-scoped cash if no explicit override
  const resolvedPaymentAccount = input.paymentAccount ?? await getCashAccountCode(branchId)

  try {
    await getAccountId(input.expenseAccount)
    await getAccountId(resolvedPaymentAccount)
  } catch (e) {
    return { success: false as const, error: (e as Error).message }
  }

  const [record] = await db
    .insert(expense_records)
    .values({
      branch_id:       branchId,
      created_by:      session.user.id,
      amount:          String(input.amount),
      expense_account: input.expenseAccount,
      payment_account: resolvedPaymentAccount,
      description:     input.description,
      receipt_url:     input.receiptUrl ?? null,
      status:          'pending',
    })
    .returning()

  return { success: true as const, record }
}

// ── approveExpense ──────────────────────────────────
export async function approveExpense(input: { expenseId: string }) {
  const session = await getServerSession(authOptions)
  if (!session?.user) return { success: false as const, error: 'Unauthorized' }

  const role = (session.user.role ?? '').toLowerCase()
  if (!['admin', 'super_admin', 'admin/owner', 'manager'].includes(role)) {
    return { success: false as const, error: 'Manager role required' }
  }

  const [expense] = await db
    .select()
    .from(expense_records)
    .where(eq(expense_records.id, input.expenseId))
    .limit(1)

  if (!expense) return { success: false as const, error: 'Expense not found' }
  if (expense.status !== 'pending') {
    return { success: false as const, error: `Cannot approve expense with status: ${expense.status}` }
  }

  // If the stored payment_account is the legacy global '1010', resolve it
  // to the branch-scoped cash account for proper branch-level tracking.
  let resolvedPaymentAccount = expense.payment_account
  if (resolvedPaymentAccount === '1010') {
    resolvedPaymentAccount = await getCashAccountCode(expense.branch_id)
  }

  const entry = await createJournalEntry({
    description: `Expense: ${expense.description}`,
    referenceSource: 'EXPENSE',
    referenceId: expense.id,
    branchId: expense.branch_id,
    autoGenerated: false,
    createdBy: session.user.id,
    lines: [
      { accountCode: expense.expense_account, debit: Number(expense.amount), description: expense.description },
      { accountCode: resolvedPaymentAccount, credit: Number(expense.amount), description: 'Payment from cash/bank' },
    ],
  })

  await db
    .update(expense_records)
    .set({ status: 'approved', approved_by: session.user.id, approved_at: new Date(), journal_entry_id: entry.id })
    .where(eq(expense_records.id, input.expenseId))

  return { success: true as const, entry }
}

export async function settleVendorPayment(input: {
  poId: string
  amount: number
  paymentMethod: string  // bank|cash|upi|cheque
  referenceNumber?: string
  notes?: string
  paymentDate?: Date
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) {
    return { success: false as const, error: 'Unauthorized' }
  }

  const role = (session.user.role ?? '').toLowerCase()
  const isManager = ['admin', 'super_admin', 'admin/owner',
    'manager'].includes(role)
  if (!isManager) {
    return {
      success: false as const,
      error: 'Manager role required to record payments'
    }
  }

  if (input.amount <= 0) {
    return {
      success: false as const,
      error: 'Payment amount must be greater than 0'
    }
  }

  // Get PO with vendor info
  const [po] = await db
    .select({
      id: purchase_orders.id,
      po_number: purchase_orders.po_number,
      vendor_id: purchase_orders.vendor_id,
      branch_id: purchase_orders.branch_id,
      total_amount: purchase_orders.total_amount,
      status: purchase_orders.status,
    })
    .from(purchase_orders)
    .where(eq(purchase_orders.id, input.poId))
    .limit(1)

  if (!po) {
    return { success: false as const, error: 'PO not found' }
  }

  // Only settled/received POs can be paid — check before AP query
  const payableStatuses = [
    'received', 'partially_received',
    'approved', 'PARTIALLY_RETURNED', 'RETURNED'
  ]
  if (!payableStatuses.includes(po.status ?? '')) {
    return {
      success: false as const,
      error: `Cannot record payment for PO with status: ${po.status}`
    }
  }

  // Derive outstanding AP from journal lines on account 2010 for this PO.
  // Net AP = SUM(credit) - SUM(debit) across all posted journal entries
  // referencing this PO. This correctly reflects:
  //   + GRN journals      (CR 2010 = amount owed)
  //   - Debit notes       (DR 2010 = AP reduced)
  //   - Short-close reversals (DR 2010 = AP reduced)
  //   - Prior vendor payments (DR 2010 = AP settled)
  const apBalanceResult = await db.execute(sql`
    SELECT
      COALESCE(SUM(jl.credit), 0) AS total_cr,
      COALESCE(SUM(jl.debit),  0) AS total_dr
    FROM journal_lines jl
    JOIN journal_entries je
      ON je.id = jl.journal_entry_id
    JOIN accounts a
      ON a.id = jl.account_id
    WHERE je.reference_id = ${input.poId}
      AND je.status = 'posted'
      AND a.code = '2010'
  `)

  const apRows = (apBalanceResult as any).rows ?? apBalanceResult
  const totalCR = Number(apRows[0]?.total_cr ?? 0)
  const totalDR = Number(apRows[0]?.total_dr ?? 0)
  const remainingBalance = Number((totalCR - totalDR).toFixed(2))

  if (remainingBalance <= 0) {
    return {
      success: false as const,
      error: `No outstanding AP balance for this PO — already fully settled or reversed`,
    }
  }

  if (input.amount > remainingBalance + 0.01) {
    return {
      success: false as const,
      error: `Payment ₹${input.amount.toLocaleString('en-IN')} exceeds outstanding AP balance ₹${remainingBalance.toLocaleString('en-IN')}`,
    }
  }

  // Determine payment account from method — branch-scoped cash if applicable
  const paymentAccountCode =
    input.paymentMethod === 'cash' ? await getCashAccountCode(po.branch_id) : '1020'

  // Determine payment description
  const methodLabels: Record<string, string> = {
    bank: 'Bank Transfer', cash: 'Cash Payment',
    upi: 'UPI Transfer', cheque: 'Cheque Payment',
  }
  const methodLabel = methodLabels[input.paymentMethod]
    ?? input.paymentMethod

  const paymentDate = input.paymentDate ?? new Date()

  try {
    // Post journal entry
    // DR 2010 Accounts Payable (reduces what we owe)
    // CR 1010/1020 Cash/Bank (reduces our cash)
    const entry = await createJournalEntry({
      date: paymentDate,
      description: `Vendor payment: ${po.po_number} — ${methodLabel}${input.referenceNumber ? ` (Ref: ${input.referenceNumber})` : ''}`,
      referenceSource: 'PAYMENT',
      referenceId: po.id,
      branchId: po.branch_id!,
      autoGenerated: false,
      createdBy: session.user.id,
      lines: [
        {
          accountCode: '2010',
          debit: input.amount,
          description: `AP settlement: ${po.po_number}`,
        },
        {
          accountCode: paymentAccountCode,
          credit: input.amount,
          description: `${methodLabel} to vendor`,
        },
      ],
    })

    // Record the payment
    const [payment] = await db
      .insert(vendor_payments)
      .values({
        po_id: input.poId,
        vendor_id: po.vendor_id!,
        branch_id: po.branch_id!,
        amount: String(input.amount),
        payment_method: input.paymentMethod,
        reference_number: input.referenceNumber ?? null,
        payment_date: paymentDate,
        notes: input.notes ?? null,
        journal_entry_id: entry.id,
        created_by: session.user.id,
      })
      .returning()

    return { success: true as const, payment, entry }
  } catch (error) {
    console.error('PAYMENT ERROR:', error)
    return {
      success: false as const,
      error: (error as Error).message
    }
  }
}

// ── getVendorPayments ───────────────────────────────

export async function getVendorPayments(input?: {
  poId?: string
  branchId?: string
}) {
  const session = await getServerSession(authOptions)
  if (!session?.user) {
    return { success: false as const, error: 'Unauthorized' }
  }

  try {
    const payments = await db
      .select({
        id:              vendor_payments.id,
        poId:            vendor_payments.po_id,
        vendorId:        vendor_payments.vendor_id,
        branchId:        vendor_payments.branch_id,
        amount:          vendor_payments.amount,
        paymentMethod:   vendor_payments.payment_method,
        referenceNumber: vendor_payments.reference_number,
        paymentDate:     vendor_payments.payment_date,
        notes:           vendor_payments.notes,
        createdAt:       vendor_payments.created_at,
        poNumber:        purchase_orders.po_number,
        vendorName:      vendors.name,
      })
      .from(vendor_payments)
      .leftJoin(purchase_orders,
        eq(vendor_payments.po_id, purchase_orders.id))
      .leftJoin(vendors,
        eq(vendor_payments.vendor_id, vendors.id))
      .where(
        input?.poId
          ? eq(vendor_payments.po_id, input.poId)
          : input?.branchId
          ? eq(vendor_payments.branch_id, input.branchId)
          : undefined
      )
      .orderBy(desc(vendor_payments.payment_date))

    return { success: true as const, payments }
  } catch (error) {
    return {
      success: false as const,
      error: (error as Error).message
    }
  }
}

